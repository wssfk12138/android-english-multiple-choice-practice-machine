import assert from 'node:assert/strict'
import { fixture, plain } from './helpers/vocabulary-request-fixture.mjs'
const f = fixture(); f.seed(250, 'failed'); f.seed(1, 'failed', 251)
f.db.exec("UPDATE vocabulary_entries SET user_edited=1,common_meaning='protected' WHERE id=251")
const runner = f.load('platform/android/vocabulary-request-runner')
const legacy = f.load('platform/android/vocabulary-translation-runner')
await runner.requestVocabularyRun('translation', [1,251], { explicit: true, retry: true })
await Promise.all([legacy.startVocabularyTranslationWorker(), legacy.startVocabularyTranslationWorker()])
assert.deepEqual(f.calls.map(call => plain(call.ids)), [[1]])
assert.equal(f.db.prepare('SELECT common_meaning FROM vocabulary_entries WHERE id=251').get().common_meaning, 'protected')
await runner.requestVocabularyRun('translation', Array.from({length:249}, (_,i)=>i+2), { explicit:true, retry:true })
await f.settle()
assert.equal(f.calls.length, 5)
assert.equal(new Set(f.calls.flatMap(call => call.ids)).size, 33)
await legacy.queueAndStartVocabularyTranslations([100], 'practice_exit'); await f.settle()
assert.equal(f.calls.length, 5)
assert.equal(f.db.prepare("SELECT count(*) n FROM vocabulary_entries WHERE translation_status='queued'").get().n, 217)
f.close()
console.log('PASS exact-ID retry, explicit full scope bounded by four requests, shared worker, manual protection, no automatic renewal')
