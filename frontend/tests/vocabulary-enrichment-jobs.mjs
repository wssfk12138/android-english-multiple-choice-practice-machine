import assert from 'node:assert/strict'
import { test } from 'node:test'
import { fixture, validWord, plain } from './helpers/vocabulary-request-fixture.mjs'
test('451-word inventory is complete and idempotent; persistent pause sends nothing', async () => {
  const f=fixture(); f.seed(451,'ready')
  const jobs=f.load('platform/android/vocabulary-enrichment-runner')
  await jobs.pauseVocabularyEnrichment(); await jobs.inventoryVocabularyEnrichment()
  assert.equal((await jobs.vocabularyEnrichmentProgress()).queued,451)
  await jobs.inventoryVocabularyEnrichment(); await jobs.startVocabularyEnrichmentWorker()
  assert.equal(f.calls.length,0)
  await f.load('platform/android/vocabulary-request-recovery').recoverVocabularyRequests(f.raw)
  await jobs.startVocabularyEnrichmentWorker(); assert.equal(f.calls.length,0)
  f.close()
})
test('one enrichment request does not start other jobs; manual meanings and checked arrays survive', async () => {
  const f=fixture(); f.seed(2,'ready')
  f.db.exec("UPDATE vocabulary_entries SET user_edited=1,common_meaning='manual' WHERE id=1")
  const jobs=f.load('platform/android/vocabulary-enrichment-runner')
  await jobs.queueVocabularyEnrichment(1); await jobs.queueVocabularyEnrichment(1); await jobs.queueVocabularyEnrichment(2)
  f.setResponse(ids=>validWord(ids[0]))
  await jobs.requestVocabularyEnrichment(1); await f.settle()
  assert.deepEqual(f.calls.map(call=>plain(call.ids)),[[1]])
  assert.equal(f.db.prepare('SELECT common_meaning FROM vocabulary_entries WHERE id=1').get().common_meaning,'manual')
  assert.equal(f.db.prepare('SELECT state FROM vocabulary_enrichment_jobs WHERE entry_id=2').get().state,'queued')
  await jobs.inventoryVocabularyEnrichment()
  assert.equal(f.db.prepare('SELECT state FROM vocabulary_enrichment_jobs WHERE entry_id=1').get().state,'ready')
  f.close()
})
test('context/edit conflict is skipped, not ready and not automatically paid again', async () => {
  const f=fixture(); f.seed(1,'ready')
  const jobs=f.load('platform/android/vocabulary-enrichment-runner')
  f.setResponse(ids=>validWord(ids[0]))
  f.onRequest(async()=>f.db.exec("UPDATE vocabulary_entries SET common_meaning='edited' WHERE id=1"))
  await jobs.requestVocabularyEnrichment(1); await f.settle()
  const result=JSON.parse(f.db.prepare('SELECT result FROM vocabulary_request_attempts').get().result)
  assert.equal(result.skipped[1],'edited_or_context_changed'); assert.equal(result.modelValidIds.length,1)
  assert.equal(f.db.prepare('SELECT state FROM vocabulary_enrichment_jobs').get().state,'failed')
  assert.equal(f.calls.length,1); f.close()
})
test('failed enrichment stops and only explicit selected retry is released', async () => {
  const f=fixture(); f.seed(3,'ready')
  const jobs=f.load('platform/android/vocabulary-enrichment-runner')
  await jobs.inventoryVocabularyEnrichment()
  f.setResponse(ids=>({entryId:ids[0],commonMeaning:'incomplete'}))
  await jobs.startVocabularyEnrichmentWorker(); await f.settle()
  assert.equal(f.calls.length,1)
  assert.equal((await jobs.vocabularyEnrichmentProgress()).queued,2)
  await jobs.queueVocabularyEnrichment(1,true); await jobs.startVocabularyEnrichmentWorker()
  assert.equal(f.calls.length,1)
  f.setResponse(ids=>validWord(ids[0]))
  await jobs.retryPendingVocabularyEnrichments([1]); await f.settle()
  assert.deepEqual(f.calls.map(call=>plain(call.ids)),[[1],[1]])
  assert.equal((await jobs.vocabularyEnrichmentProgress()).queued,2)
  f.close()
})
