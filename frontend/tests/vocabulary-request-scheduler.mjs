test('before-send cleanup refuses inflight or superseded attempts and ignores late callbacks after a clean abort', async () => {
  for (const kind of ['inflight', 'superseded', 'aborted']) {
    const f = fixture(); f.seed(1)
    const store = f.load('platform/android/vocabulary-request-store')
    const config = await f.load('platform/android/vocabulary-request-config').vocabularyConfiguration()
    await store.createVocabularyRun('translation', [1], config, 'automatic')
    const claim = await store.claimVocabularyBatch(config)
    if (kind === 'inflight') await store.markVocabularySent(claim, config)
    if (kind === 'superseded') f.db.exec("UPDATE vocabulary_request_heads SET attempt_id='newer'")
    if (kind !== 'aborted') {
      await assert.rejects(store.abortVocabularyBeforeSend(claim, 'configuration'), /保持停止/)
      assert.equal(f.db.prepare('SELECT state FROM vocabulary_request_attempts').get().state, kind === 'inflight' ? 'inflight' : 'intent')
      assert.equal(f.db.prepare('SELECT translation_status FROM vocabulary_entries').get().translation_status, 'translating')
    } else {
      await store.pauseVocabularyRequests()
      await store.abortVocabularyBeforeSend(claim, 'stopped')
      const before = f.db.prepare('SELECT * FROM vocabulary_request_attempts').get()
      const late = f.load('platform/android/vocabulary-request-result').vocabularyBatchResult([1])
      late.failure = 'unknown'
      await f.database.transaction(async db => {
        assert.equal(await store.currentVocabularyAttempt(db, claim), false)
        await store.commitVocabularyResult(db, claim, late)
      })
      assert.deepEqual(f.db.prepare('SELECT * FROM vocabulary_request_attempts').get(), before)
      assert.equal((await store.vocabularyRequestStatus()).reason, 'user')
      assert.equal((await store.vocabularyRequestStatus()).pending.translation, 1)
    }
    assert.equal((await store.vocabularyRequestStatus()).used, 1)
    f.close()
  }
})

