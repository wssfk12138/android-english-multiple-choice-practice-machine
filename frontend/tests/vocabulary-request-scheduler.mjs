for (const task of ['translation', 'enrichment']) for (const reason of ['user', 'configuration', 'content_changed']) {
  test(`${task}: ${reason} after claim preserves unsent queue and reservation until explicit continue`, async () => {
    const f = fixture(); f.seed(2, task === 'translation' ? 'pending' : 'ready')
    if (task === 'enrichment') f.db.exec('INSERT INTO vocabulary_enrichment_jobs(entry_id) VALUES(1),(2)')
    const runner = f.load('platform/android/vocabulary-request-runner')
    const store = f.load('platform/android/vocabulary-request-store')
    f.db.exec('UPDATE vocabulary_request_gate SET used=3')
    f.beforeSend(async () => {
      assert.equal(f.db.prepare('SELECT state FROM vocabulary_request_attempts').get().state, 'intent')
      assert.equal((await store.vocabularyRequestStatus()).used, 4)
      if (reason === 'user') await store.pauseVocabularyRequests()
      if (reason === 'configuration') { f.state.key = 'changed-synthetic-key'; await store.invalidateVocabularyConfiguration() }
      if (reason === 'content_changed') f.db.exec("UPDATE vocabulary_entries SET common_meaning='private changed content' WHERE id=1")
    })
    await runner.requestVocabularyRun(task); await f.settle()
    assert.equal(f.calls.length, 0)
    const status = await store.vocabularyRequestStatus()
    assert.equal(status.reason, reason)
    assert.equal(status.pending[task], 2)
    assert.deepEqual(plain(status.retryIds[task]), [])
    assert.equal(status.used, 4) // Intent reservations are never refunded.
    assert.equal(f.db.prepare('SELECT used FROM vocabulary_request_runs').get().used, 1)
    const attempt = f.db.prepare('SELECT state,category,result FROM vocabulary_request_attempts').get()
    assert.equal(attempt.state, 'done')
    assert.equal(attempt.category, `not_sent_${reason}`)
    assert.equal(JSON.stringify(attempt).includes('private changed content'), false)
    assert.equal(f.db.prepare("SELECT COUNT(*) n FROM vocabulary_request_members WHERE state='queued'").get().n, 2)
    if (task === 'translation') assert.equal(f.db.prepare("SELECT COUNT(*) n FROM vocabulary_entries WHERE translation_status='queued'").get().n, 2)
    else {
      assert.equal(f.db.prepare("SELECT COUNT(*) n FROM vocabulary_enrichment_jobs WHERE state='queued'").get().n, 2)
      assert.equal(f.db.prepare("SELECT COUNT(*) n FROM vocabulary_entries WHERE translation_status='ready'").get().n, 2)
    }
    f.beforeSend(async () => {})
    await f.load('platform/android/vocabulary-request-recovery').recoverVocabularyRequests(f.raw)
    await runner.requestVocabularyRun(task); await f.settle()
    assert.equal(f.calls.length, 0)
    assert.equal((await store.vocabularyRequestStatus()).unknown.length, 0)
    assert.equal((await store.vocabularyRequestStatus()).reason, reason)
    assert.equal((await store.vocabularyRequestStatus()).used, 4)
    f.setResponse((ids, kind) => kind === 'translation' ? { translations: ids.map(validWord) } : validWord(ids[0]))
    await runner.requestVocabularyRun(task, [1,2], { explicit: true, source: 'continue' }); await f.settle()
    assert.deepEqual(f.calls.flatMap(call => plain(call.ids)), [1,2])
    f.close()
  })
}

